export type TranslationKey = keyof (typeof TRANSLATIONS)['en'];

export function t(key: TranslationKey | string, fallback?: string): string {
  const currentLocale = useUI.getState().locale ?? 'en';
  const langDict = (TRANSLATIONS[currentLocale] || TRANSLATIONS.en) as Record<string, string>;
  return langDict[key] || (TRANSLATIONS.en as Record<string, string>)[key] || fallback || key;
}

export function useTranslation() {
  const locale = useUI((s) => s.locale);
  const setLocale = useUI((s) => s.setLocale);

  const translate = (key: TranslationKey | string, fallback?: string): string => {
    const langDict = (TRANSLATIONS[locale] || TRANSLATIONS.en) as Record<string, string>;
    return langDict[key] || (TRANSLATIONS.en as Record<string, string>)[key] || fallback || key;
  };

  return {
    t: translate,
    locale,
    setLocale,
    languages: LANGUAGES,
  };
}
